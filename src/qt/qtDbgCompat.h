// Differences between Qt 5.7 and Qt 6 used by the Qt debugger

#ifndef QTDBGCOMPAT_H
#define QTDBGCOMPAT_H

#include <QtGlobal>
#include <QFontMetrics>
#include <QMouseEvent>
#include <QString>

inline int dbgTextWidth(const QFontMetrics& fm, const QString& text)
{
#if QT_VERSION >= QT_VERSION_CHECK(5, 11, 0)
    return fm.horizontalAdvance(text);
#else
    return fm.width(text);
#endif
}

inline QPoint dbgMousePos(const QMouseEvent* event)
{
#if QT_VERSION >= QT_VERSION_CHECK(6, 0, 0)
    return event->position().toPoint();
#else
    return event->pos();
#endif
}

#endif // QTDBGCOMPAT_H
